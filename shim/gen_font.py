#!/usr/bin/env python3
"""Generate font.h (ASCII 0x20-0x7e, 8x16) from the Spleen 8x16 BDF.

Usage: gen_font.py spleen-8x16.bdf   (writes font.h in the current directory)
Source: https://github.com/fcambus/spleen commit 5116f8eac7f65da2cfa169626ec43b5d041665fe
(release 2.2.0), file spleen-8x16.bdf sha256
b38b32a66920068965a3101f98071d310c5c74659fe86e55d346140770f8f6e8. BSD-2-Clause.
"""
import sys
glyphs, enc, rows = {}, None, None
for ln in open(sys.argv[1]).read().splitlines():
    if ln.startswith('ENCODING '):
        enc = int(ln.split()[1])
    elif ln.startswith('BBX '):
        assert ln == 'BBX 8 16 0 -4', ln
    elif ln == 'BITMAP':
        rows = []
    elif ln == 'ENDCHAR':
        assert len(rows) == 16
        glyphs[enc] = rows
        rows = None
    elif rows is not None:
        rows.append(int(ln, 16))
out = ['/* Glyphs: Spleen 8x16 2.2.0, Copyright (c) 2018-2026, Frederic Cambus, BSD 2-Clause.',
       ' * Source: https://github.com/fcambus/spleen @ 5116f8eac7f65da2cfa169626ec43b5d041665fe',
       ' * (spleen-8x16.bdf). Licence text: LICENSES/Spleen-BSD-2-Clause.txt; see THIRD_PARTY.md.',
       ' * Generated by gen_font.py. */',
       'static const unsigned char font8x16[95][16] = {']
for c in range(0x20, 0x7f):
    out.append('\t{' + ','.join('0x%02x' % b for b in glyphs[c]) + '},')
out.append('};')
open('font.h', 'w').write('\n'.join(out) + '\n')
