#!/usr/bin/env python3
"""trace2seq.py - golden register trace -> spec DRAFT rows (never a spec, never production data).

Usage: tools/trace2seq.py GOLDEN.csv -o OUT.json [--from-seq N] [--to-seq M] [--writes-only]
Input: the REAL golden format, the CSV of `tools/trace-diff golden-regs DIR --block wifi|gpu|dpu` (tools/trace-diff:14-18): `#` header lines, then
`seq,ts,src,mark,caller,op,width,space,win,addr,val`; op W|R|CW|CR; space bar0|bar2|cfg|mmio|va. It is parsed by tools/lint_g2_stores.py parse_golden (one
parser for both tools). The Gemini free-text format (`W <addr> <val>`), its invented SoC block table and its step guessing are gone.

Output: JSON with `"status": "draft"`; EVERY row carries `"status": "draft"`, `"tag": "guess"` and `"restore": "TODO"` (rule 5/7): a human must cite
each row, decide its restore/teardown and move it into docs/specs/SPEC-<BLOCK>.md before it can become a table row. The block name of a row is its trace
space upper-cased (BAR0, BAR2, CFG, MMIO, VA): the mapping to a soc.json block is NOT done here (unknown without the VA->PA join; the golden-4 join is
hashed, AP-132). A new step starts where the trace `mark` column changes. Reads are kept as read_only rows, config rows as blk CFG.
It refuses (exit 2, `RESULT: ERROR file:line: reason`) any input line it cannot parse, an empty selection, and any output path that resolves
inside this repo's soc/ or xnu/ directory. It never writes anywhere else than -o (required).
Caller: none yet (drafting aid; the driver adds a documented-command line in docs/PORT-METHOD.md step "spec" or an allowlist row; its output is read by no tool or gate).

RESULT: PASS draft rows=N steps=S -> OUT   (exit 0)      RESULT: ERROR ...   (exit 2)
"""
import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import lint_g2_stores as lint  # noqa: E402

FORBIDDEN = [os.path.join(ROOT, "soc"), os.path.join(ROOT, "xnu")]
KIND = {"W": "mmio_write", "CW": "mmio_write", "R": "read_only", "CR": "read_only"}   # kinds of soc/google/gs101/wlan_seq.json "kinds"


def forbidden_out(path):
    """True when path (after resolving symlinks and '..', also for a not yet existing file) lies inside soc/ or xnu/ of this repo."""
    real = os.path.realpath(path)
    for d in FORBIDDEN:
        rd = os.path.realpath(d)
        if real == rd or real.startswith(rd + os.sep):
            return True
    return False


def draft(csv_lines, src, from_seq=None, to_seq=None, writes_only=False):
    rows, _ = lint.parse_golden(csv_lines, src)
    out, steps, step, last_mark = [], {}, -1, None
    for r in rows:
        if from_seq is not None and r["seq"] < from_seq:
            continue
        if to_seq is not None and r["seq"] > to_seq:
            continue
        if writes_only and r["op"] not in ("W", "CW"):
            continue
        mark, ts, win = r["mark"], r["ts"], r["win"]
        if mark != last_mark or step < 0:
            step, last_mark = step + 1, mark
            steps[str(step)] = "trace mark %r (draft grouping, rename by hand)" % mark
        out.append({
            "id": len(out), "step": step, "kind": KIND[r["op"]], "blk": "CFG" if r["space"] == "cfg" else r["space"].upper(),
            "win": win, "off": r["addr"], "width": r["width"], "value": r["val"] if r["val"] is not None else 0, "mask": 0xFFFFFFFF,
            "cite": "golden CSV %s seq %d ts %s caller %s" % (os.path.basename(src), r["seq"], ts, r["caller"] or "-"),
            "status": "draft", "tag": "guess", "restore": "TODO",
        })
    if not out:
        raise lint.ParseError(src, "the selection holds no row (range or --writes-only excludes everything)")
    return {"_doc": "DRAFT generated by tools/trace2seq.py; not a spec, not for soc/ or xnu/; every row is a guess until a human cites it and fills restore",
            "status": "draft", "source": os.path.basename(src), "steps": steps, "rows": out}


def main(argv=None):
    p = argparse.ArgumentParser(prog="trace2seq", description=__doc__.split("\n")[0])
    p.add_argument("input")
    p.add_argument("-o", "--output", required=True)
    p.add_argument("--from-seq", type=int)
    p.add_argument("--to-seq", type=int)
    p.add_argument("--writes-only", action="store_true")
    a = p.parse_args(argv)
    if a.output and forbidden_out(a.output):
        print("RESULT: ERROR refusing to write %s: inside soc/ or xnu/ (drafts never go there)" % a.output)
        return 2
    try:
        with open(a.input, errors="replace") as f:
            lines = f.readlines()
    except OSError as e:
        print("RESULT: ERROR %s" % e)
        return 2
    try:
        seq = draft(lines, a.input, a.from_seq, a.to_seq, a.writes_only)
    except lint.ParseError as e:
        print("RESULT: ERROR %s" % e)
        return 2
    seq["source_sha256"] = hashlib.sha256("".join(lines).encode("utf-8", "replace")).hexdigest()
    with open(a.output, "w") as f:
        f.write(json.dumps(seq, indent=1) + "\n")
    print("RESULT: PASS draft rows=%d steps=%d -> %s" % (len(seq["rows"]), len(seq["steps"]), a.output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
