#!/usr/bin/env python3
"""Independent reference for shim/wlan_4way_host_test.c (T-5dc1): builds a WPA2-PSK 4-way transcript with python hmac/hashlib and
`cryptography` (AES key wrap), NOT with the shim code, and prints the C constants for shim/wlan_4way_vectors.h.
Usage: tools/gen_wlan_4way_vectors.py > shim/wlan_4way_vectors.h   (needs the `cryptography` package; test inputs are public/made up).
Frame layout read from IEEE 802.11-2016 12.7.2 (offsets in sweet_wlan_join.h header comment)."""
import hashlib, hmac, struct, sys
from cryptography.hazmat.primitives.keywrap import aes_key_wrap

PASS, SSID = b"ThisIsAPassword", b"ThisIsASSID"          # IEEE 802.11i-2004 Annex H.4 test case 2
AA = bytes.fromhex("020000aa0001"); SPA = bytes.fromhex("020000bb0002")   # locally administered, made up
ANONCE = bytes(range(0xe0, 0x100)); SNONCE = bytes(range(0xc0, 0xe0))
RSNE = bytes.fromhex("3014" "0100" "000fac04" "0100" "000fac04" "0100" "000fac02" "0000")
GTK = bytes(range(0x50, 0x60)); GTK_ID = 1

pmk = hashlib.pbkdf2_hmac("sha1", PASS, SSID, 4096, 32)

def prf(key, label, data, nbytes):
    out = b""; i = 0
    while len(out) < nbytes:
        out += hmac.new(key, label + b"\x00" + data + bytes([i]), hashlib.sha1).digest(); i += 1
    return out[:nbytes]

data = min(AA, SPA) + max(AA, SPA) + min(ANONCE, SNONCE) + max(ANONCE, SNONCE)
ptk = prf(pmk, b"Pairwise key expansion", data, 48)
kck, kek, tk = ptk[:16], ptk[16:32], ptk[32:48]

def key_frame(ver, info, keylen, rc, nonce, kd, kck=None, mic_on=False):
    body = bytes([2]) + struct.pack(">HH", info, keylen) + struct.pack(">Q", rc) + nonce + bytes(16) + bytes(8) + bytes(8) \
        + bytes(16) + struct.pack(">H", len(kd)) + kd
    pdu = bytes([ver, 3]) + struct.pack(">H", len(body)) + body
    if mic_on:
        mic = hmac.new(kck, pdu, hashlib.sha1).digest()[:16]       # MIC field is zero in pdu at this point
        pdu = pdu[:81] + mic + pdu[97:]
    return pdu

def eth(src, dst, pdu): return dst + src + b"\x88\x8e" + pdu

m1 = key_frame(1, 0x008a, 16, 1, ANONCE, b"")
kd = RSNE + bytes([0xdd, 0x16, 0x00, 0x0f, 0xac, 0x01, GTK_ID, 0x00]) + GTK
kd += b"\xdd" + b"\x00" * (8 - len(kd) % 8 - 1)        # pad: dd 00 ... to a multiple of 8
wrapped = aes_key_wrap(kek, kd)
m3 = key_frame(1, 0x13ca, 16, 2, ANONCE, wrapped, kck, True)
m2 = key_frame(1, 0x010a, 0, 1, SNONCE, RSNE, kck, True)
m4 = key_frame(1, 0x030a, 0, 2, bytes(32), b"", kck, True)

def c(name, b):
    return "static const uint8_t %s[%d] = {%s};\n" % (name, len(b), ",".join("0x%02x" % x for x in b))

sys.stdout.write("/* generated by tools/gen_wlan_4way_vectors.py (independent python reference); do not edit */\n")
for n, b in (("V_AA", AA), ("V_SPA", SPA), ("V_ANONCE", ANONCE), ("V_SNONCE", SNONCE), ("V_RSNE", RSNE), ("V_GTK", GTK),
             ("V_PMK", pmk), ("V_PTK", ptk), ("V_M1", eth(AA, SPA, m1)), ("V_M2", eth(SPA, AA, m2)), ("V_M3", eth(AA, SPA, m3)),
             ("V_M4", eth(SPA, AA, m4))):
    sys.stdout.write(c(n, b))
sys.stdout.write("#define V_PASS \"%s\"\n#define V_SSID \"%s\"\n#define V_GTK_ID %d\n" % (PASS.decode(), SSID.decode(), GTK_ID))
